package com.astryxion.astryxionshats.common.hat;

/**
 * Determines how hats are handled in gameplay
 */
public enum HatMode {

    /**
     * All hats are unlocked immediately
     * Creative-style cosmetic usage
     */
    COSMETIC,

    /**
     * Hats must be unlocked by killing mobs wearing them
     */
    HUNTING
}
